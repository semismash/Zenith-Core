#!/usr/bin/env python3
"""Zenith Core - make a DEBUG copy of bios.s that prints one letter at each stage of the boot, for board bring-up.

    python3 patch_bios_debug.py src/firmware/bios.s build/bios/bios_debug.s        (`make bios-debug` does this)

Markers (the UART is driven directly, only t5/t6 are touched, and only at points where they are free):
    a b c d e   after the registers / ALU / control flow / memory / stack self tests      (letters printed even if a test failed)
    P           the BIOS's own UART test byte 0x50, sent between 'e' and 'f'
    f           st_evaluate      g  reset (BIOS constants + stack set up)      h  update      i  idle (every time the BIOS returns to idle)
A healthy boot therefore prints   a b c d e P f g h i   followed by the BIOS state update bytes F0 00.
Where the letters stop is where the BIOS stops making progress on the board.
"""
import re
import sys

MARKERS = [
    ("selftest_reg_fail",  "a"),
    ("selftest_alu_fail",  "b"),
    ("selftest_ctrl_fail", "c"),
    ("selftest_mem_fail",  "d"),
    ("selftest_sp_fail",   "e"),
    ("st_evaluate",        "f"),
    ("reset",              "g"),
    ("update",             "h"),
    ("idle",               "i"),
]

MACRO = """# ---- bring-up debug markers (generated by patch_bios_debug.py, not part of the real BIOS) ----
.macro dbg ch
    lui     t6, 0x80000
dbg_w\\@:
    lbu     t5, 0(t6)
    andi    t5, t5, 2
    bnez    t5, dbg_w\\@
    li      t5, \\ch
    sb      t5, 8(t6)
.endm
# ---------------------------------------------------------------------------------------------
"""

def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, dst = sys.argv[1], sys.argv[2]
    lines = open(src, newline="").read().splitlines()
    missing = []
    out = [MACRO]
    for line in lines:
        out.append(line)
    # insert the markers after their labels (a label may carry a trailing comment)
    result = []
    done = set()
    for line in out:
        result.append(line)
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*):", line)
        if m:
            for label, ch in MARKERS:
                if m.group(1) == label and label not in done:
                    result.append("    dbg     %d              # marker '%s'" % (ord(ch), ch))
                    done.add(label)
    for label, ch in MARKERS:
        if label not in done:
            missing.append(label)
    open(dst, "w", newline="\n").write("\n".join(result) + "\n")
    print("wrote %s with %d markers" % (dst, len(done)))
    if missing:
        print("WARNING: label(s) not found, no marker there: " + ", ".join(missing))

if __name__ == "__main__":
    main()
